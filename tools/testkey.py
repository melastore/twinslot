#!/usr/bin/env python3
"""Writes src/testkey.h from third_party/avb/testkey_rsa2048.pem (needs openssl and avbtool)."""
import os
import re
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PEM = os.path.join(ROOT, "third_party", "avb", "testkey_rsa2048.pem")


def array(name, data):
    lines = ["static const u8 %s[%d] = {" % (name, len(data))]
    for i in range(0, len(data), 16):
        lines.append("\t" + ", ".join("0x%02x" % x for x in data[i:i + 16]) + ",")
    return "\n".join(lines + ["};"])


def main():
    with tempfile.TemporaryDirectory() as tmp:
        pub = os.path.join(tmp, "pub.bin")
        subprocess.run(["avbtool", "extract_public_key", "--key", PEM, "--output", pub], check=True)
        with open(pub, "rb") as f:
            public = f.read()
    text = subprocess.run(["openssl", "rsa", "-in", PEM, "-noout", "-text"], capture_output=True, text=True,
                          check=True).stdout
    m = re.search(r"privateExponent:\s*\n((?:\s+[0-9a-f:]+\n)+)", text)
    d = bytes.fromhex(re.sub(r"[\s:]", "", m.group(1))).lstrip(b"\0")
    assert len(public) == 520 and len(d) == 256
    sys.stdout.write("""/*
 * The AOSP test key, external/avb/test/data/testkey_rsa2048.pem (Apache-2.0,
 * copy in third_party/avb). It is public; CK7n ROMs sign vbmeta with it and
 * the bootloader accepts it, so twinslot re-signs edited slots with it.
 * Generated by tools/testkey.py.
 */
#ifndef TWINSLOT_TESTKEY_H
#define TWINSLOT_TESTKEY_H

#include "common.h"

/* AvbRSAPublicKeyHeader + n + rr, as avbtool extract_public_key writes it. */
%s

/* The private exponent, big-endian. */
%s

#endif
""" % (array("testkey_avb_public", public), array("testkey_d", d)))


if __name__ == "__main__":
    main()
